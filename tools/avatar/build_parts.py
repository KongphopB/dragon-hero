"""
Avatar sprite generator: the only script to run after changing character art.

    python tools/avatar/build_parts.py            -> rewrites js/data/avatar-sprites.js
    python tools/avatar/build_parts.py --preview  -> also writes tools/avatar/preview.png

Where things are drawn (all on a 64x64 grid, recoloured in the game via key colours):
    shapes/        smooth-shape parts: body, hair, outfits, races, accessories, hats, weapons
    pixel_parts.py tiny hand-pixelled parts: eyes, mouths, blush, glasses, eyepatch, flower, pets
    hires.py       smooth-shape renderer (8x supersample -> lit 64x64 pixel art)
    shade.py       colour ramps + key colours (ramp() must match js/ui/avatar-color.js)
    preview.py     contact sheet for --preview
Loose PNGs of every part also go to tools/avatar/out/ (gitignored) for inspection.
"""
import base64
import io
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pixel_parts as PX  # noqa: E402
import shade as SH  # noqa: E402
import shapes as SHP  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "out"          # loose PNGs for inspection (gitignored)
BUNDLE = ROOT / "js" / "data" / "avatar-sprites.js"     # what the game loads


# Base colours offered in the creator (indexes saved in the player's look).
def build_palettes():
    skin = [[253, 226, 200], [240, 190, 147], [209, 143, 94], [148, 90, 56],   # 4 human tones
            [236, 214, 204], [212, 88, 88], [150, 112, 212], [94, 140, 212]]
    hair = [[44, 52, 74], [128, 74, 36], [226, 178, 40], [200, 48, 44], [86, 80, 210], [222, 226, 236],
            [236, 112, 168], [64, 168, 98], [168, 176, 194], [60, 184, 216]]
    eye = [
        [56, 86, 152],   # Stardew slate blue
        [96, 56, 36],    # warm brown
        [186, 118, 34],  # honey amber
        [44, 152, 86],   # emerald green
        [44, 172, 218],  # sky blue
        [134, 72, 206],  # violet
        [204, 48, 62],   # ruby red
        [228, 178, 36],  # gold
        [230, 102, 160], # rose pink
        [48, 52, 68],    # obsidian dark slate
    ]
    cloth = [(214, 44, 44), (232, 96, 24), (222, 168, 20), (106, 166, 28), (32, 160, 84), (20, 148, 136),
             (20, 142, 186), (44, 104, 226), (88, 78, 222), (146, 60, 220), (214, 52, 128), (84, 96, 120)]
    return {"skin": skin, "hair": hair, "eye": eye, "cloth": [list(c) for c in cloth]}


def main():
    # pixel-drawn pieces (faces, small accessories, pets) go through the 2D shader;
    # bodies, hair, outfits, races, weapons and larger accessories are built as smooth shapes (shapes.py)
    pixel = {}
    for fn in (PX.build_faces, PX.build_pets):
        pixel.update(fn())
    pixel.update(PX.build_face_accessories())
    parts = PX.shade_all(pixel)
    parts.update(SHP.build_all(parts))
    pals = build_palettes()
    OUT.mkdir(parents=True, exist_ok=True)
    sprites = {}
    for name, im in sorted(parts.items()):
        im.save(OUT / (name + ".png"), optimize=True)
        buf = io.BytesIO()
        im.save(buf, "PNG", optimize=True)
        sprites[name] = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
    js = ("// GENERATED by tools/avatar/build_parts.py: do not edit by hand.\n"
          "window.DH = window.DH || {};\n"
          "window.DH.AVATAR_KEYS = " + json.dumps(SH.KEYS6) + ";\n"
          "window.DH.AVATAR_PALETTES = " + json.dumps(pals) + ";\n"
          "window.DH.AVATAR_SPRITES = " + json.dumps(sprites, indent=0) + ";\n")
    BUNDLE.write_text(js, encoding="utf-8")
    print("wrote %d parts to %s (%d KB)" % (len(parts), BUNDLE, len(js) // 1024))
    if "--preview" in sys.argv:
        from preview import preview
        p = Path(__file__).with_name("preview.png")
        preview(parts, pals).save(p)
        print("preview:", p)


if __name__ == "__main__":
    main()
